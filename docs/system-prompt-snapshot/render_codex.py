#!/usr/bin/env python3
"""Render a two-frame Codex capture and reconcile item attribution (tiktoken 0.14.0).

Usage: uv run --no-project --with tiktoken==0.14.0 python render_codex.py DIR
Request/response JSON is canonical; all .md files and summary.json are derived.
Only the observed prewarm + generating-turn shape is accepted.
"""

import json
import re
import sys
from pathlib import Path

import tiktoken


def dump(value):
    return json.dumps(value, indent=2, ensure_ascii=False)


def count(text):
    return len(tiktoken.get_encoding("o200k_harmony").encode(text, disallowed_special=()))


def verify_session(root, prewarm, turn, result):
    records = [json.loads(line) for line in (root / "session.jsonl").read_text().splitlines()]
    base = records[0]["payload"]["base_instructions"]["text"]
    if base != prewarm["input"][1]["content"][0]["text"]:
        raise ValueError("Logged base instructions differ from the request")
    logged = [r["payload"] for r in records if r["type"] == "response_item"]
    if logged[:-1] != turn["input"]:
        raise ValueError("Logged input conversation differs from captured messages")
    # The log adds content_item_kinds and drops the response's output metadata.
    visible = lambda item: {k: item[k] for k in ("type", "id", "role", "content", "phase", "status") if k in item}
    if visible(logged[-1]) != visible(result["output"][0]):
        raise ValueError("Logged assistant output differs from captured output")
    usage = next(r["payload"] for r in records if r["type"] == "token_usage_record")
    if usage["response_id"] != result["id"] or usage["usage"]["input_tokens"] != result["usage"]["input_tokens"]:
        raise ValueError("Session token usage disagrees with the response")
    events = [json.loads(line) for line in (root / "exec.jsonl").read_text().splitlines()]
    if events[-1]["usage"] != {k: v for k, v in usage["usage"].items() if k != "total_tokens"}:
        raise ValueError("CLI token usage disagrees with the session")
    return {"base_instructions": True, "all_conversation_items": True, "token_usage": True,
            "cli_usage": True, "session_id": records[0]["payload"]["id"]}


def original_session(root):
    records = [json.loads(line) for line in (root / "original-vscode-session.jsonl").read_text().splitlines()]
    meta = records[0]["payload"]
    rows = [{"kind": "model.base_instructions", "text_tokens_estimate": count(meta["base_instructions"]["text"])}]
    for record in records:
        if record["type"] != "response_item" or record["payload"].get("role") == "assistant":
            continue
        item = record["payload"]
        kinds = item.get("internal_chat_message_metadata_passthrough", {}).get("content_item_kinds", [])
        for i, content in enumerate(item["content"]):
            rows.append({"kind": kinds[i] if i < len(kinds) else "unknown", "text_tokens_estimate": count(content["text"])})
    usage = next(r["payload"]["usage"] for r in records if r["type"] == "token_usage_record")
    return {"session_id": meta["id"], "usage": usage, "rows": rows,
            "separately_counted_text_tokens_estimate": sum(row["text_tokens_estimate"] for row in rows),
            "wire_tools_and_item_attribution_available": False}


def render(root):
    requests = [json.loads(p.read_text()) for p in sorted(root.glob("*-request.json"))]
    results = [json.loads(p.read_text())["response"] for p in sorted(root.glob("*-result.json"))]
    if len(requests) != 2 or len(results) != 2:
        raise ValueError("Expected exactly two requests and two completed responses")
    prewarm, turn = requests
    if prewarm.get("generate") is not False or turn.get("previous_response_id") != results[0]["id"]:
        raise ValueError("Broken prewarm/turn response linkage")
    if results[1]["previous_response_id"] != results[0]["id"]:
        raise ValueError("Broken terminal response linkage")
    items = prewarm["input"] + turn["input"]
    output = results[1]["output"]
    attribution = results[1]["usage"]["attribution"]["items"]
    if set(attribution) != {x["id"] for x in items + output}:
        raise ValueError("Attribution does not cover exactly the input and output items")
    rows = []
    prompt = ["# Captured Codex input", "", "Generated by `render_codex.py`; JSON frames are canonical.", ""]
    for label, req in zip(("Prewarm", "Generating turn"), requests):
        params = {k: v for k, v in req.items() if k != "input"}
        prompt += [f"## {label} parameters", "", "```json", dump(params), "```", ""]
    tool_dir = root / "tools"
    tool_dir.mkdir(exist_ok=True)
    tool_rows = []
    for item in items + output:
        actual = attribution[item["id"]]
        if item["type"] == "additional_tools":
            rows.append({"id": item["id"], "kind": "additional_tools", "api_input_tokens": actual["input_tokens"]})
            prompt += ["## additional_tools (developer)", ""]
            for namespace in item["tools"]:
                if namespace.get("type") != "namespace":
                    raise ValueError("Unexpected tool outside a namespace")
                # Keep namespace attributes even when its description is empty.
                prompt += ["```json", dump({k: v for k, v in namespace.items() if k != "tools"}), "```", ""]
                for tool in namespace["tools"]:
                    name = f'{namespace["name"]}.{tool["name"]}'
                    if not re.fullmatch(r"[\w.-]+", name):
                        raise ValueError("Unsafe tool filename")
                    text = tool.get("description", "")
                    attrs = {k: v for k, v in tool.items() if k != "description"}
                    (tool_dir / f"{name}.md").write_text(f"# {name}\n\n{text}\n\n```json\n{dump(attrs)}\n```\n")
                    metric = {"name": name, "description_tokens_estimate": count(text),
                              "compact_json_tokens_estimate": count(json.dumps(tool, ensure_ascii=False, separators=(",", ":")))}
                    tool_rows.append(metric)
                    prompt += [f"- [{name}](tools/{name}.md)"]
            prompt.append("")
            continue
        kinds = item.get("internal_chat_message_metadata_passthrough", {}).get("content_item_kinds", [])
        for i, content in enumerate(item["content"]):
            if content["type"] not in {"input_text", "output_text"}:
                raise ValueError("Unexpected non-text content")
            text = content["text"]
            kind = kinds[i] if i < len(kinds) else ("assistant.output" if item in output else "unknown")
            api = actual["content"][i]
            rows.append({"id": item["id"], "content_index": i, "kind": kind,
                         "role": item["role"], "characters": len(text),
                         "text_tokens_estimate": count(text), "api_input_tokens": api["input_tokens"],
                         "api_output_tokens": api["output_tokens"]})
            prompt += [f'## {kind} ({item["role"]})', "", text, ""]
        if sum(c["input_tokens"] for c in actual["content"]) != actual["input_tokens"]:
            raise ValueError("Content attribution does not sum to item attribution")
    usage = results[1]["usage"]
    actual_input = sum(r["api_input_tokens"] for r in rows)
    if actual_input != usage["input_tokens"]:
        raise ValueError("Input attribution does not sum to reported input usage")
    if sum(v["output_tokens"] for v in attribution.values()) != usage["output_tokens"]:
        raise ValueError("Output attribution does not sum to output usage")
    summary = {"session_verification": verify_session(root, prewarm, turn, results[1]),
               "original_vscode": original_session(root),
               "encoding": "o200k_harmony", "tiktoken_version": tiktoken.__version__,
               "model": turn["model"], "usage": usage, "prewarm_usage": results[0]["usage"],
               "rows": rows, "tools": tool_rows, "attributed_input_total": actual_input,
               "unattributed_input_tokens": usage["input_tokens"] - actual_input,
               "input_text_tokens_estimate": sum(r.get("text_tokens_estimate", 0) for r in rows if r.get("role") != "assistant"),
               "tool_compact_json_tokens_estimate": count(json.dumps(items[0]["tools"], ensure_ascii=False, separators=(",", ":"))),
               "serialized_request_json_tokens_estimate": [count(json.dumps(r, ensure_ascii=False, separators=(",", ":"))) for r in requests]}
    (root / "prompt.md").write_text("\n".join(prompt))
    (root / "summary.json").write_text(dump(summary) + "\n")
    return summary


if __name__ == "__main__":
    render(Path(sys.argv[1]))
