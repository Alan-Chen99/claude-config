# Transcript parsing & LLM summarization
# ---------------------------------------------------------------------------


def read_transcript_tail(path: str, max_bytes: int = TRANSCRIPT_TAIL_BYTES) -> list[str]:
    """Read the last *max_bytes* of a transcript file, returning whole lines.

    Seeks to end-minus-max_bytes so we never load the full file (transcripts
    can be tens of MB).  The first partial line is discarded.
    """
    p = Path(path)
    size = p.stat().st_size  # raises FileNotFoundError / OSError
    with p.open("r", encoding="utf-8", errors="replace") as f:
        if size > max_bytes:
            f.seek(size - max_bytes)
            f.readline()  # discard first partial line
        return f.readlines()


def extract_context(lines: list[str]) -> str:
    """Parse JSONL transcript lines into a compact conversation summary."""
    parts: list[str] = []
    total = 0
    parsed = 0
    skipped_types: dict[str, int] = {}

    for line in lines:
        if total >= CONTEXT_MAX_CHARS:
            break
        try:
            entry = json.loads(line)
        except (json.JSONDecodeError, TypeError):
            continue
        parsed += 1

        entry_type = entry.get("type", "?")
        if entry_type not in ("user", "assistant"):
            skipped_types[entry_type] = skipped_types.get(entry_type, 0) + 1
            continue

        message = entry.get("message", {})
        role = message.get("role", "")
        content = message.get("content", "")

        if role == "user":
            text = _extract_user_text(content)
            if text:
                part = f"User: {text[:500]}"
                parts.append(part)
                total += len(part)

        elif role == "assistant" and isinstance(content, list):
            for block in content:
                if total >= CONTEXT_MAX_CHARS:
                    break
                if not isinstance(block, dict):
                    continue
                part = _extract_assistant_block(block)
                if part:
                    parts.append(part)
                    total += len(part)

    combined = "\n".join(parts)
    log.debug(
        "extract_context: %d lines, %d parsed, %d parts, %d chars, skipped types: %s",
        len(lines), parsed, len(parts), len(combined), skipped_types,
    )
    return combined[-CONTEXT_MAX_CHARS:]


def _extract_user_text(content) -> str:
    """Extract readable text from a user message content field."""
    if isinstance(content, str):
        return content.strip()
    if isinstance(content, list):
        texts: list[str] = []
        for block in content:
            if not isinstance(block, dict):
                continue
            if block.get("type") == "text":
                texts.append(block.get("text", ""))
            elif block.get("type") == "tool_result":
                body = block.get("content", "")
                if isinstance(body, str) and body:
                    texts.append(f"[tool result: {body[:100]}]")
        return " ".join(texts).strip()
    return ""


def _extract_assistant_block(block: dict) -> str | None:
    """Extract a single readable part from an assistant content block."""
    btype = block.get("type")
    if btype == "text":
        text = block.get("text", "").strip()
        if text:
            return f"Assistant: {text[:500]}"
    elif btype == "tool_use":
        name = block.get("name", "?")
        inp = block.get("input", {})
        if name == "Bash" and "command" in inp:
            detail = inp["command"][:200]
        elif name in ("Read", "Write", "Edit", "Glob", "Grep"):
            detail = (inp.get("file_path") or inp.get("pattern") or "")[:200]
        else:
            detail = str(inp)[:100]
        return f"Tool: {name}({detail})"
    return None


def generate_summary(api_key: str, context: str, hook_type: str) -> str:
    """Call OpenRouter claude-haiku for a 1-line summary."""
    prompt = SUMMARY_PROMPTS.get(hook_type, SUMMARY_PROMPTS["idle"])
    # Wrap transcript so the model treats it as data, not a live conversation
    user_msg = (
        "--- BEGIN TRANSCRIPT ---\n"
        f"{context}\n"
        "--- END TRANSCRIPT ---\n\n"
        "Write the notification summary:"
    )
    payload = json.dumps({
        "model": "anthropic/claude-haiku-4.5",
        "messages": [
            {"role": "system", "content": prompt},
            {"role": "user", "content": user_msg},
        ],
        "max_tokens": 80,
        "temperature": 0,
    }).encode()

    req = Request(
        "https://openrouter.ai/api/v1/chat/completions",
        data=payload,
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        method="POST",
    )

    try:
        resp_bytes = urlopen(req, timeout=LLM_TIMEOUT).read()
    except HTTPError as exc:
        body = ""
        try:
            body = exc.read().decode("utf-8", errors="replace")[:100]
        except Exception:
            pass
        raise RuntimeError(f"OpenRouter {exc.code}: {body}") from exc
    except URLError as exc:
        if "timed out" in str(exc.reason).lower():
            raise RuntimeError(f"OpenRouter timeout ({LLM_TIMEOUT}s)") from exc
        raise RuntimeError(f"OpenRouter error: {exc.reason}") from exc

    try:
        data = json.loads(resp_bytes)
        return data["choices"][0]["message"]["content"].strip()
    except (json.JSONDecodeError, KeyError, IndexError, TypeError) as exc:
        raise RuntimeError(f"Bad OpenRouter response: {exc}") from exc


def _format_location(cwd: str) -> str:
    """Return a compact 'user@host:path' location string."""
    try:
        user = getpass.getuser()
    except Exception:
        user = "?"
    try:
        host = socket.gethostname().split(".")[0]  # short hostname
    except Exception:
        host = "?"
    prefix = f"{user}@{host}"
    if cwd:
        # Show last 2 path components for brevity: "repos/claude-config"
        parts = Path(cwd).parts
        short = str(Path(*parts[-2:])) if len(parts) >= 2 else cwd
        return f"{prefix}:{short}"
    return prefix


def was_interrupted(transcript_path: str) -> bool:
    """Heuristic: check if the agent turn ended due to interruption (e.g. Ctrl+C).

    Returns True if the last assistant message has pending tool_use calls
    without corresponding tool_result responses, suggesting the user
    interrupted the agent mid-task.
    """
    if not transcript_path:
        return False
    try:
        lines = read_transcript_tail(transcript_path, max_bytes=8000)
    except (FileNotFoundError, OSError):
        return False

    entries = []
    for line in lines:
        try:
            entries.append(json.loads(line))
        except (json.JSONDecodeError, TypeError):
            continue

    if not entries:
        return False

    # Walk backward: find the last assistant entry
    last_assistant_idx = None
    for i in range(len(entries) - 1, -1, -1):
        if entries[i].get("type") == "assistant":
            last_assistant_idx = i
            break

    if last_assistant_idx is None:
        return False

    content = entries[last_assistant_idx].get("message", {}).get("content", [])
    if not isinstance(content, list):
        return False

    has_tool_use = any(
        isinstance(b, dict) and b.get("type") == "tool_use"
        for b in content
    )
    if not has_tool_use:
        return False

    # Check if any subsequent entry contains tool_result
    for entry in entries[last_assistant_idx + 1 :]:
        user_content = entry.get("message", {}).get("content", [])
        if isinstance(user_content, list) and any(
            isinstance(b, dict) and b.get("type") == "tool_result"
            for b in user_content
        ):
            return False  # tool results found → not interrupted

    # tool_use without tool_result → likely interrupted
    return True


def is_mid_turn_stop(transcript_path: str) -> bool:
    """Return True if this Stop event is from a mid-turn subagent completion.

    When the main agent finishes, the last assistant entry is a text response
    (no tool_use). When a subagent finishes mid-turn, the last assistant entry
    dispatched tools, tool results came back, but no new assistant text follows.
    """
    if not transcript_path:
        return False
    try:
        lines = read_transcript_tail(transcript_path, max_bytes=8000)
    except (FileNotFoundError, OSError):
        return False

    entries = []
    for line in lines:
        try:
            entries.append(json.loads(line))
        except (json.JSONDecodeError, TypeError):
            continue

    if not entries:
        return False

    # Find the last assistant entry
    last_assistant_idx = None
    for i in range(len(entries) - 1, -1, -1):
        if entries[i].get("type") == "assistant":
            last_assistant_idx = i
            break

    if last_assistant_idx is None:
        return False

    content = entries[last_assistant_idx].get("message", {}).get("content", [])
    if not isinstance(content, list):
        return False

    has_agent_tool = any(
        isinstance(b, dict) and b.get("type") == "tool_use" and b.get("name") == "Agent"
        for b in content
    )
    if not has_agent_tool:
        return False  # No Agent dispatch → not a mid-turn subagent stop

    # Tool_use exists — check if tool_results came back but agent hasn't
    # produced a new response yet (mid-turn subagent completion).
    has_tool_result = False
    for entry in entries[last_assistant_idx + 1:]:
        if entry.get("type") == "assistant":
            return False  # Agent continued after tools — this is a normal stop
        if entry.get("type") == "user":
            user_content = entry.get("message", {}).get("content", [])
            if isinstance(user_content, list) and any(
                isinstance(b, dict) and b.get("type") == "tool_result"
                for b in user_content
            ):
                has_tool_result = True

    return has_tool_result


def last_pending_tool(transcript_path: str) -> str | None:
    """Return the name of the last pending tool_use (no tool_result yet), or None."""
    try:
        lines = read_transcript_tail(transcript_path, max_bytes=8000)
    except (FileNotFoundError, OSError):
        return None

    entries = []
    for line in lines:
        try:
            entries.append(json.loads(line))
        except (json.JSONDecodeError, TypeError):
            continue

    # Walk backward to find the last assistant entry
    for i in range(len(entries) - 1, -1, -1):
        if entries[i].get("type") != "assistant":
            continue
        content = entries[i].get("message", {}).get("content", [])
        if not isinstance(content, list):
            continue
        # Find the last tool_use block in this assistant message
        tool_name = None
        for block in content:
            if isinstance(block, dict) and block.get("type") == "tool_use":
                tool_name = block.get("name")
        if tool_name:
            return tool_name
        break  # only check the last assistant entry

    return None


def build_notification(transcript_path: str | None, hook_type: str, cwd: str = "") -> str:
    """Orchestrate summary generation. Returns body text or [err] message.

    All results (success or error) include a location suffix line.
    """
    log.debug("build_notification: path=%r type=%r cwd=%r", transcript_path, hook_type, cwd)
    location = _format_location(cwd)

    api_key = get_api_key()
    if not api_key:
        return f"[err] No API key (set OPENROUTER_API_KEY in /repos/claude-config/.env)\n{location}"

    if not transcript_path:
        log.warning("no transcript_path in hook input")
        return f"[err] No transcript_path in hook input\n{location}"

    try:
        lines = read_transcript_tail(transcript_path)
        log.debug("read %d lines from transcript (%s)", len(lines), transcript_path)
    except FileNotFoundError:
        log.warning("transcript not found: %s", transcript_path)
        return f"[err] Transcript not found: {transcript_path}\n{location}"
    except OSError as exc:
        log.warning("transcript read error: %s", exc)
        return f"[err] Transcript read error: {exc}\n{location}"

    context = extract_context(lines)
    if not context.strip():
        # Early in session — no conversation yet, send without summary
        return location

    try:
        summary = generate_summary(api_key, context, hook_type)
        return f"{summary}\n{location}"
    except RuntimeError as exc:
        return f"[err] {exc}\n{location}"


