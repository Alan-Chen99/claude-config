def do_notify(args: argparse.Namespace) -> None:
    if args.delayed:
        # Re-invoked child: sleep, build summary, publish, clean up
        time.sleep(DELAY_SECONDS)
        if donefile_path(args.session_id).exists():
            pass
        elif (topic_url := get_topic_url()):
            body = build_notification(args.transcript_path, args.hook_type or args.type or "idle", args.cwd)
            publish(topic_url, args.message_title, body, args.message_tag)
        try:
            pidfile_path(args.session_id).unlink()
        except FileNotFoundError:
            pass
        return

    # Parent: read stdin, kill pending, spawn delayed child
    hook_input = read_hook_input()
    session_id = hook_input.get("session_id", "unknown")
    kill_pending(session_id)

    if donefile_path(session_id).exists():
        return

    topic_url = get_topic_url()
    if not topic_url:
        return

    transcript_path = hook_input.get("transcript_path", "")

    # Derive type from stdin JSON (notification_type) or CLI --type flag
    raw_type = hook_input.get("notification_type", "") or args.type or ""
    # Map Claude Code notification_type values to our internal types
    _TYPE_MAP = {
        "permission_prompt": "permission",
        "idle_prompt": "idle",
        "elicitation_dialog": "question",
    }
    notify_type = _TYPE_MAP.get(raw_type, raw_type) if raw_type else "idle"
    if notify_type not in NOTIFY_TYPES:
        notify_type = "idle"
    # AskUserQuestion fires notification_type=idle_prompt (older Claude Code
    # versions used permission_prompt). Detect via pending tool and relabel
    # so the notification reads "Question" instead of "Idle" / "Permission".
    if notify_type in ("permission", "idle") and transcript_path:
        pending = last_pending_tool(transcript_path)
        if pending == "AskUserQuestion":
            log.debug("reclassified %s -> question (pending tool: AskUserQuestion)", notify_type)
            notify_type = "question"
    title, tag = NOTIFY_TYPES.get(notify_type, NOTIFY_TYPES["idle"])
    cwd = hook_input.get("cwd", "")
    project = Path(cwd).name if cwd else ""
    if project:
        title = f"{title} ({project})"

    child = subprocess.Popen(
        [
            sys.executable,
            "-m", "claude_config.ntfy_hook",
            "--action", "notify",
            "--delayed",
            "--session-id", session_id,
            "--message-title", title,
            "--message-tag", tag,
            "--transcript-path", transcript_path,
            "--hook-type", notify_type,
            "--cwd", cwd,
        ],
        start_new_session=True,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )

    pidfile_path(session_id).write_text(str(child.pid))


def do_stop(args: argparse.Namespace) -> None:
    if args.delayed:
        # Re-invoked child: build summary and publish immediately
        if (topic_url := get_topic_url()):
            body = build_notification(args.transcript_path, "stop", args.cwd)
            publish(topic_url, args.message_title, body, args.message_tag)
        return

    # Parent: read stdin, kill pending, touch donefile, spawn async child
    hook_input = read_hook_input()
    session_id = hook_input.get("session_id", "unknown")
    kill_pending(session_id)

    # Already sent a "Done" for this session — don't spam.
    if donefile_path(session_id).exists():
        log.debug("suppressed stop notification: donefile exists (session %s)", session_id)
        return

    transcript_path = hook_input.get("transcript_path", "")

    # Skip "done" notification if the agent was interrupted (e.g. Ctrl+C)
    if was_interrupted(transcript_path):
        log.debug("suppressed stop notification: interrupted (session %s)", session_id)
        return

    # Skip mid-turn subagent completions (tool dispatched, result back,
    # but agent hasn't produced its next response yet).
    if is_mid_turn_stop(transcript_path):
        log.debug("suppressed stop notification: mid-turn subagent stop (session %s)", session_id)
        return

    # Create donefile only after confirming this is a real stop,
    # so mid-turn suppression doesn't block subsequent idle notifications.
    donefile_path(session_id).touch()

    topic_url = get_topic_url()
    if not topic_url:
        return
    cwd = hook_input.get("cwd", "")
    title = "Claude Code: Done"
    project = Path(cwd).name if cwd else ""
    if project:
        title = f"{title} ({project})"

    subprocess.Popen(
        [
            sys.executable,
            "-m", "claude_config.ntfy_hook",
            "--action", "stop",
            "--delayed",
            "--session-id", session_id,
            "--message-title", title,
            "--message-tag", "white_check_mark",
            "--transcript-path", transcript_path,
            "--hook-type", "stop",
            "--cwd", cwd,
        ],
        start_new_session=True,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )


def do_cancel(_args: argparse.Namespace) -> None:
    hook_input = read_hook_input()
    session_id = hook_input.get("session_id", "unknown")
    kill_pending(session_id)
    # Task-notifications (background task completions) are system-generated,
    # not real user re-engagement. Keep the donefile so do_stop doesn't
    # re-fire "Done" for each stale background task.
    prompt = hook_input.get("prompt", "")
    if prompt.lstrip().startswith("<task-notification>"):
        log.debug("cancel: keeping donefile for task-notification (session %s)", session_id)
        return
    try:
        donefile_path(session_id).unlink()
    except FileNotFoundError:
        pass


def main() -> None:
    parser = argparse.ArgumentParser(description="Claude Code ntfy notification hook")
    parser.add_argument(
        "--action",
        required=True,
        choices=["notify", "stop", "cancel"],
    )
    parser.add_argument(
        "--type",
        choices=["permission", "idle", "question"],
        help="Notification type (for --action notify)",
    )

    # Internal flags for delayed re-invocation
    parser.add_argument("--delayed", action="store_true", help=argparse.SUPPRESS)
    parser.add_argument("--session-id", help=argparse.SUPPRESS)
    parser.add_argument("--message-title", help=argparse.SUPPRESS)
    parser.add_argument("--message-tag", default="bell", help=argparse.SUPPRESS)
    parser.add_argument("--transcript-path", help=argparse.SUPPRESS)
    parser.add_argument("--hook-type", help=argparse.SUPPRESS)
    parser.add_argument("--cwd", default="", help=argparse.SUPPRESS)

    args = parser.parse_args()

    handlers = {
        "notify": do_notify,
        "stop": do_stop,
        "cancel": do_cancel,
    }
    handlers[args.action](args)


if __name__ == "__main__":
    main()
