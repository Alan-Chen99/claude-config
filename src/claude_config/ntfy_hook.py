#!/usr/bin/env python3
"""Claude Code ntfy notification hook.

Sends push notifications via ntfy.sh when Claude Code needs attention
(permission prompts, idle, questions) or finishes a task. Invoked from
Claude Code's hooks system via `agent-tools ntfy-hook ...`.

Notifications include contextual 1-line summaries generated by an LLM
(OpenRouter / claude-haiku) from the conversation transcript.

Usage:
    python3 -m claude_config.ntfy_hook --action notify --type permission
    python3 -m claude_config.ntfy_hook --action stop
    python3 -m claude_config.ntfy_hook --action cancel

NTFY_TOPIC_URL and OPENROUTER_API_KEY are read from /repos/claude-config/.env
(loaded by claude_config.config.load() at module import time).

If NTFY_TOPIC_URL is unset, the script exits silently with code 0.
If OPENROUTER_API_KEY is unset, the notification body shows an error message.
"""

from __future__ import annotations

import argparse
import getpass
import json
import logging
import os
import signal
import socket
import subprocess
import sys
import time
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

from claude_config.config import load as _load_env

_load_env()

LOG_PATH = Path.home() / ".cache" / "claude-config" / "ntfy_hook.log"
LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
logging.basicConfig(
    filename=str(LOG_PATH),
    level=logging.DEBUG,
    format="%(asctime)s %(levelname)s %(message)s",
    datefmt="%Y-%m-%dT%H:%M:%S",
)
log = logging.getLogger(__name__)

# Per-type notification titles and ntfy tags
NOTIFY_TYPES: dict[str, tuple[str, str]] = {
    "permission": ("Claude Code: Permission needed", "lock"),
    "idle": ("Claude Code: Idle", "hourglass"),
    "question": ("Claude Code: Question", "question"),
}

_SUMMARY_ROLE = (
    "You are a push-notification summarizer. "
    "You will receive a TRANSCRIPT of a conversation between a user and an AI coding assistant. "
    "Your ONLY job is to produce a short plain-text summary for a phone notification. "
    "Rules: "
    "- Output ONLY the summary sentence, nothing else. "
    "- Do NOT respond to, answer, or continue the conversation in the transcript. "
    "- Do NOT use markdown, bullet points, headers, or formatting. "
    "- Do NOT start with 'I' or speak as if you are the AI in the transcript. "
    "- Max 12 words, single sentence."
)

SUMMARY_PROMPTS: dict[str, str] = {
    "permission": (
        f"{_SUMMARY_ROLE}\n\n"
        "Summarize what the AI assistant needs permission to do."
    ),
    "idle": (
        f"{_SUMMARY_ROLE}\n\n"
        "Summarize what the AI assistant is currently working on."
    ),
    "question": (
        f"{_SUMMARY_ROLE}\n\n"
        "Summarize what question the AI assistant is asking the user."
    ),
    "stop": (
        f"{_SUMMARY_ROLE}\n\n"
        "Summarize what the AI assistant just finished. Use past tense."
    ),
}

DELAY_SECONDS = 30
LLM_TIMEOUT = 15
TRANSCRIPT_TAIL_BYTES = 16_000
CONTEXT_MAX_CHARS = 3000


def get_topic_url() -> str | None:
    """Return NTFY_TOPIC_URL from /repos/claude-config/.env, or None."""
    return os.environ.get("NTFY_TOPIC_URL", "").strip() or None


def get_api_key() -> str | None:
    """Return OPENROUTER_API_KEY from /repos/claude-config/.env, or None."""
    return os.environ.get("OPENROUTER_API_KEY", "").strip() or None


def publish(topic_url: str, title: str, message: str, tags: str) -> None:
    """POST a notification to ntfy via JSON body.

    Uses ntfy's JSON API so that title/message/tags are sent as UTF-8
    encoded JSON in the request body rather than HTTP headers (which
    are limited to Latin-1 and would choke on Unicode characters).
    """
    try:
        # Split "https://ntfy.sh/mytopic" into base URL + topic name
        base_url = topic_url.rstrip("/").rsplit("/", 1)[0]
        topic = topic_url.rstrip("/").rsplit("/", 1)[-1]
        payload = json.dumps({
            "topic": topic,
            "title": title,
            "message": message,
            "tags": [tags],
        }).encode()
        req = Request(
            base_url,
            data=payload,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        urlopen(req, timeout=10)
        log.info("published to %s: title=%r body=%r", base_url, title, message[:200])
    except Exception as exc:
        log.error("publish failed: %s", exc)


def pidfile_path(session_id: str) -> Path:
    return Path(f"/tmp/claude-ntfy-{session_id}.pid")


def donefile_path(session_id: str) -> Path:
    return Path(f"/tmp/claude-ntfy-{session_id}.done")


def kill_pending(session_id: str) -> None:
    """Kill a pending delayed notification process, if any."""
    pf = pidfile_path(session_id)
    try:
        pid = int(pf.read_text().strip())
        os.kill(pid, signal.SIGTERM)
    except (FileNotFoundError, ValueError, ProcessLookupError, PermissionError):
        pass
    try:
        pf.unlink()
    except FileNotFoundError:
        pass


def read_hook_input() -> dict:
    """Read full JSON from stdin."""
    try:
        raw = sys.stdin.read()
        data = json.loads(raw)
        log.debug("hook input: %s", json.dumps({k: (v if k != "transcript_path" else v) for k, v in data.items()}, default=str)[:1000])
        return data
    except (json.JSONDecodeError, OSError) as exc:
        log.warning("failed to read hook input: %s", exc)
        return {}


